-- MySQL 8: 같은 승인된 스키마에서 DDL 전·후에 실행하는 메타데이터 조회.
SELECT DATABASE() AS schema_name,
       @@SESSION.default_storage_engine AS default_engine,
       @@SESSION.foreign_key_checks AS foreign_key_checks,
       @@SESSION.lock_wait_timeout AS lock_wait_timeout,
       @@SESSION.sql_mode AS sql_mode;
SELECT DEFAULT_CHARACTER_SET_NAME, DEFAULT_COLLATION_NAME
FROM INFORMATION_SCHEMA.SCHEMATA
WHERE SCHEMA_NAME = DATABASE();

-- 적용 전 세 문서 테이블이 모두 없어야 하며 user의 id·account_state 계약을 대조한다.
SELECT TABLE_NAME, TABLE_TYPE, ENGINE, TABLE_COLLATION
FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME IN ('user','document_translation_job','document_translation_batch','document_translation_object_write')
ORDER BY TABLE_NAME;
SELECT COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE, COLUMN_KEY, COLUMN_DEFAULT
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME = 'user'
  AND COLUMN_NAME IN ('id', 'account_state')
ORDER BY COLUMN_NAME;

-- 완성 구조의 열·형식·기본값·생성식과 인덱스 컬럼/순서를 대조한다.
SELECT TABLE_NAME, ORDINAL_POSITION, COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE,
       COLUMN_DEFAULT, EXTRA, GENERATION_EXPRESSION, CHARACTER_SET_NAME, COLLATION_NAME
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME IN ('document_translation_job','document_translation_batch','document_translation_object_write')
ORDER BY TABLE_NAME, ORDINAL_POSITION
LIMIT 128;
SELECT TABLE_NAME, INDEX_NAME, NON_UNIQUE, SEQ_IN_INDEX, COLUMN_NAME,
       COLLATION, SUB_PART, INDEX_TYPE, IS_VISIBLE
FROM INFORMATION_SCHEMA.STATISTICS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME IN ('document_translation_job','document_translation_batch','document_translation_object_write')
ORDER BY TABLE_NAME, INDEX_NAME, SEQ_IN_INDEX
LIMIT 128;

-- 문서 테이블의 제약 및 외래 키 간접 대상까지 확인한다.
SELECT TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE
FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS
WHERE CONSTRAINT_SCHEMA = DATABASE()
  AND TABLE_NAME IN ('document_translation_job','document_translation_batch','document_translation_object_write')
ORDER BY TABLE_NAME, CONSTRAINT_NAME
LIMIT 128;
SELECT u.TABLE_NAME, u.CONSTRAINT_NAME, u.ORDINAL_POSITION, u.COLUMN_NAME,
       u.REFERENCED_TABLE_SCHEMA, u.REFERENCED_TABLE_NAME, u.REFERENCED_COLUMN_NAME,
       r.UPDATE_RULE, r.DELETE_RULE
FROM INFORMATION_SCHEMA.KEY_COLUMN_USAGE u
JOIN INFORMATION_SCHEMA.REFERENTIAL_CONSTRAINTS r
  ON r.CONSTRAINT_SCHEMA = u.CONSTRAINT_SCHEMA
 AND r.CONSTRAINT_NAME = u.CONSTRAINT_NAME
 AND r.TABLE_NAME = u.TABLE_NAME
WHERE u.CONSTRAINT_SCHEMA = DATABASE()
  AND u.TABLE_NAME IN ('document_translation_job','document_translation_batch','document_translation_object_write')
  AND u.REFERENCED_TABLE_NAME IS NOT NULL
ORDER BY u.TABLE_NAME, u.CONSTRAINT_NAME, u.ORDINAL_POSITION
LIMIT 128;
