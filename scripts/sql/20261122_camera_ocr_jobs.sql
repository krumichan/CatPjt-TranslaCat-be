CREATE TABLE IF NOT EXISTS camera_ocr_job (
    job_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    owner_id BIGINT NOT NULL,
    idem_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    image_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    source_lang VARCHAR(8) NOT NULL,
    image_type VARCHAR(16) NOT NULL,
    image_ciphertext MEDIUMBLOB NULL,
    result_ciphertext MEDIUMBLOB NULL,
    state VARCHAR(16) NOT NULL,
    error_code VARCHAR(40) NULL,
    attempt INT NOT NULL DEFAULT 0,
    execution_token CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    lease_until DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    deadline_at DATETIME(6) NOT NULL,
    expires_at DATETIME(6) NOT NULL,
    PRIMARY KEY (job_id),
    CONSTRAINT uk_camera_ocr_idem UNIQUE (owner_id, idem_key),
    CONSTRAINT fk_camera_ocr_owner FOREIGN KEY (owner_id) REFERENCES `user` (id) ON DELETE CASCADE,
    KEY ix_camera_ocr_owner_created (owner_id, created_at),
    KEY ix_camera_ocr_deadline (state, deadline_at),
    KEY ix_camera_ocr_expires (expires_at)
);
